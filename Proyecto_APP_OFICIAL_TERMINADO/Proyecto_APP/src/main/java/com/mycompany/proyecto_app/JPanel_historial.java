    public void cargarHistorial(){
        jTextArea1_Historial.setText("");
        try {
            BufferedReader br = new BufferedReader(new FileReader("./historial.txt"));
            
            String linea;
            
            
            while ((linea = br.readLine()) != null){
                jTextArea1_Historial.append(linea + "\n");
            }
            
            
            br.close();
        } catch (IOException IE){
            jTextArea1_Historial.setText("No existe historial");
        }
    }
    
    private void BorrarHistorial(){
            int opcion = JOptionPane.showConfirmDialog(this,
                                                        "¿Estás seguro que desea borrar todo el historial?",
                                                        "Confirmar borrado",
                                                        JOptionPane.YES_NO_OPTION,
                                                        JOptionPane.WARNING_MESSAGE
            );
            
            if (opcion == JOptionPane.YES_OPTION){
            try {
            
            jTextArea1_Historial.setText("");
            
            BufferedReader br1 = new BufferedReader(new FileReader("./historial.txt"));
            BufferedWriter bw1 = new BufferedWriter(new FileWriter("./historial.txt"));
            String linea;
            
            
            
            while((linea = br1.readLine()) != null){
                bw1.append(jTextArea1_Historial.getText());
            }
            
            br1.close();
            bw1.close();
         
            JOptionPane.showMessageDialog(this, "Historial borrado correctamente");
            
        } catch (IOException IE){
            System.out.println("No se pudo borrar el historial, porque no se encontró el fichero ");
        }
     }
                
        
    }
